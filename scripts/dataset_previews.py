"""First-rows pictures of every dataset DiaCausal uses, for slides and the report.

    .venv/bin/python scripts/dataset_previews.py    # writes docs/midsem/data/*.png and *_head.csv

Each picture shows the first 8 rows (long text cut short) with a title saying what the data is,
where it comes from and whether it is real or synthetic. Rendered as HTML tables and captured with Playwright (e2e/node_modules; set CHROMIUM_PATH to use a system Chromium). Nothing here is typed by hand: every row
is read from the file (or, for the synthetic cohort, generated with the fixed seed 0).
"""

from __future__ import annotations

import html
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from diacausal_engine import ARMS  # noqa: E402
from diacausal_engine.cohort import generate_cohort, observed_view  # noqa: E402
from diacausal_engine.config import load_params  # noqa: E402

OUT = ROOT / "docs" / "midsem" / "data"
ROWS = 8
INK, MUTED, HEAD, LINE, TRUTH = "#1c2a24", "#56635c", "#e6f2ef", "#d5dbd8", "#fdf3e1"


def fmt(col: pd.Series) -> list[str]:
    if pd.api.types.is_float_dtype(col) and (col.dropna() % 1 == 0).all():
        return [f"{v:.0f}" for v in col]
    if pd.api.types.is_float_dtype(col):
        return [f"{v:.2f}" for v in col]
    return [str(v) for v in col]


def short(s: str, n: int) -> str:
    return s if len(s) <= n else s[: n - 1] + "…"


SECTIONS: list[str] = []


def picture(df: pd.DataFrame, name: str, title: str, note: str, width: int = 38, highlight: tuple[str, ...] = ()) -> None:
    """Adds one table to the page that render() turns into docs/midsem/data/<name>.png."""
    df = df.head(ROWS)
    df.to_csv(OUT / f"{name}_head.csv", index=False)
    cols = {c: fmt(df[c]) for c in df.columns}
    head = "".join(f'<th class="{"t" if c in highlight else ""}">{html.escape(c)}</th>' for c in df.columns)
    body = "".join("<tr>" + "".join(f'<td class="{"t" if c in highlight else ""}">{html.escape(short(cols[c][i], width))}</td>'
                                    for c in df.columns) + "</tr>" for i in range(len(df)))
    SECTIONS.append(f'<section id="{name}"><h1>{html.escape(title)}</h1><table><thead><tr>{head}</tr></thead>'
                    f'<tbody>{body}</tbody></table><p>{html.escape(note)}</p></section>')


CSS = f"""body{{margin:0;background:#fff;font-family:'DejaVu Sans',Arial,sans-serif;color:{INK}}}
section{{display:inline-block;padding:18px 22px}} h1{{font-size:18px;margin:0 0 10px}}
table{{border-collapse:collapse;font-size:13px}} th,td{{border:1px solid {LINE};padding:5px 9px;text-align:left;white-space:nowrap}}
th{{background:{HEAD}}} .t{{background:{TRUTH}}} p{{font-size:12px;color:{MUTED};margin:10px 0 0;max-width:1100px;line-height:1.4}}"""


def render() -> None:
    page = OUT / "_tables.html"
    page.write_text(f"<!doctype html><meta charset=utf-8><style>{CSS}</style>" + "<br>".join(SECTIONS), encoding="utf-8")
    ids = [s.split('"')[1] for s in SECTIONS]
    js = f"""const {{chromium}} = require('playwright');
(async () => {{ const b = await chromium.launch(process.env.CHROMIUM_PATH ? {{executablePath: process.env.CHROMIUM_PATH}} : {{}}); const p = await b.newPage({{deviceScaleFactor: 2, viewport: {{width: 1600, height: 900}}}});
await p.goto('file://{page}'); for (const id of {json.dumps(ids)}) {{
await p.locator('[id="' + id + '"]').screenshot({{path: '{OUT}/' + id + '.png'}}); console.log('wrote docs/midsem/data/' + id + '.png'); }}
await b.close(); }})();"""
    subprocess.run(["node", "-e", js], check=True, cwd=ROOT / "e2e")
    page.unlink()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    params = load_params()
    full = generate_cohort(params, seed=0)
    obs = observed_view(full)
    picture(obs.drop(columns=["t1d", "dka_history", "pancreatitis_history"]), "01_synthetic_cohort",
            f"1. Synthetic cohort: first {ROWS} of {len(obs):,} patients (SYNTHETIC, observed columns only)",
            "Generated by diacausal_engine/cohort.py from data/params.yaml (seed 0); columns dka_history, pancreatitis_history and t1d (always 0) not shown. One row = one patient on metformin who was given one add-on "
            "drug ('treatment'). y = 6-month HbA1c change (percentage points); weight_change_6m in kg; hypo_6m = any low-sugar episode (1 = yes). "
            "These are the only columns the estimators see; a real hospital record would have the same ones.", width=12)
    truth = full[["age", "hba1c", "egfr", "treatment", "y", *[f"y_true_{a}" for a in ARMS], *[f"e_true_{a}" for a in ARMS]]]
    picture(truth, "02_synthetic_hidden_truth",
            "2. The same patients with their hidden answers (possible only because the data is synthetic)",
            "Shaded columns are never shown to the estimators. y_true_X = the 6-month HbA1c change this patient WOULD have had on drug X "
            "(y equals the one for the drug actually given); e_true_X = the true chance a doctor would pick X for this patient. "
            "Knowing these is what lets the benchmark grade each method.", width=10,
            highlight=tuple(c for c in truth.columns if "_true_" in c))
    rules = pd.read_csv(ROOT / "data/rules.csv")[["rule_id", "arm", "field", "op", "value", "action", "message", "source", "status"]]
    picture(rules, "03_safety_rules", f"3. Safety rules: first {ROWS} of {len(pd.read_csv(ROOT / 'data/rules.csv'))} (REAL: copied from drug labels and guidelines)",
            "data/rules.csv. Every rule has a source and a section; the engine checks them BEFORE any estimate and never estimates an excluded option.", width=34)
    entries = [(path, e) for path, e in params.entries() if path.startswith("generator.outcome.effects")]
    prm = pd.DataFrame([{"parameter": p.replace("generator.outcome.effects.", ""), "value": e["value"], "unit": e.get("unit", ""),
                         "source": e["source"], "status": e["status"]} for p, e in entries])
    counts = pd.Series([e["status"] for _, e in params.entries()]).value_counts()
    picture(prm, "04_generator_parameters", "4. Generator parameters: the drug-effect rows of data/params.yaml",
            f"All {int(counts.sum())} numbers in params.yaml carry a source and a status: "
            + ", ".join(f"{k} {int(v)}" for k, v in counts.items())
            + ". The loader refuses any number without them.", width=44)
    src = pd.read_csv(ROOT / "RAG/sources.csv")[["id", "issuer", "version", "licence_as_found", "bucket", "date_checked"]]
    picture(src, "05_rag_sources", f"5. Evidence sources: first {ROWS} of {len(pd.read_csv(ROOT / 'RAG/sources.csv'))} (REAL documents, licence-checked)",
            "RAG/sources.csv. Only rows marked cleared_ingest and checked by a named person are read into the evidence index.", width=30)
    gold = pd.read_csv(ROOT / "eval/rag_gold.csv")[["id", "question", "category", "expected_source", "doctor_review"]]
    picture(gold, "06_rag_gold_questions", "6. Evidence test set: first 8 of 60 questions (written by the team)",
            "eval/rag_gold.csv: 45 answerable, 10 out of scope (must abstain), 5 dose questions (must refuse). 20 are marked for a doctor's review.", width=60)
    nmb = pd.read_csv(ROOT / "data/reference/nmb2017.csv")
    nmb = nmb[["patient_id", "state", "district", "age", "gender", "height_cm", "weight_kg", "waist_cm",
               "diabetes_self_declared", "diabetes_father", "diabetes_mother", "hba1c"]]
    picture(nmb, "07_real_indian_nmb2017", f"7. Real Indian data: NMB-2017, first {ROWS} of {len(nmb):,} adults (REAL, CC0, reference only)",
            "Nagarathna et al. 2020, Diabetes Res Clin Pract; Mendeley Data doi:10.17632/twp8xw6p25.1 (CC0 1.0). Nationwide survey of adults at "
            "high risk of type 2 diabetes. No drug and no follow-up HbA1c, so it cannot train the engine; used to check the synthetic cohort looks real. Activity columns and zone not shown.", width=16)
    render()


if __name__ == "__main__":
    main()
